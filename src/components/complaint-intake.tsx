export function ComplaintIntakeForm({
  onDone,
  onClose,
  embedded = false,
}: {
  onDone?: (ref: string, id: string) => void;
  onClose?: () => void;
  embedded?: boolean;
}) {
  const router = useRouter();
  const toast = useToast();

  const [activePreset, setActivePreset] = useState<string>("atm-timeout");
  const [customerName, setCustomerName] = useState(demoScenarios[0].customerName);
  const [customerReference, setCustomerReference] = useState(demoScenarios[0].customerReference);
  const [customerPhone, setCustomerPhone] = useState(demoScenarios[0].customerPhone);
  const [customerEmail, setCustomerEmail] = useState(demoScenarios[0].customerEmail);
  const [accountNumber, setAccountNumber] = useState(demoScenarios[0].accountNumber);
  const [channel, setChannel] = useState(demoScenarios[0].channel);
  const [categoryCode, setCategoryCode] = useState(demoScenarios[0].categoryCode);
  const [priority, setPriority] = useState<Priority>(demoScenarios[0].priority);
  const [amount, setAmount] = useState(demoScenarios[0].amount);
  const [transactionReference, setTransactionReference] = useState(demoScenarios[0].transactionReference);
  const [summary, setSummary] = useState(demoScenarios[0].summary);
  const [narrative, setNarrative] = useState(demoScenarios[0].narrative);
  const [sendAcknowledgement, setSendAcknowledgement] = useState(true);

  const [submitting, setSubmitting] = useState(false);
  const [result, setResult] = useState<{ reference: string; complaintId: string } | null>(null);

  const applyPreset = (preset: PresetScenario) => {
    setActivePreset(preset.id);
    setCustomerName(preset.customerName);
    setCustomerReference(preset.customerReference);
    setCustomerPhone(preset.customerPhone);
    setCustomerEmail(preset.customerEmail);
    setAccountNumber(preset.accountNumber);
    setChannel(preset.channel);
    setCategoryCode(preset.categoryCode);
    setPriority(preset.priority);
    setAmount(preset.amount);
    setTransactionReference(preset.transactionReference);
    setSummary(preset.summary);
    setNarrative(preset.narrative);
  };

  const clearForm = () => {
    setActivePreset("");
    setCustomerName("");
    setCustomerReference(`CUST-NGN-${Math.floor(100000 + Math.random() * 900000)}`);
    setCustomerPhone("+234 ");
    setCustomerEmail("");
    setAccountNumber("");
    setChannel("Mobile Banking App");
    setCategoryCode("CARDS_ATM");
    setPriority("MEDIUM");
    setAmount("");
    setTransactionReference("");
    setSummary("");
    setNarrative("");
  };

  const handleSubmit = async (e: FormEvent) => {
    e.preventDefault();
    if (!summary.trim() || !narrative.trim()) {
      toast("Please provide both an issue summary and narrative description.", "error");
      return;
    }

    setSubmitting(true);
    try {
      const categoryLabel = categoryOptions.find((c) => c.code === categoryCode)?.label || categoryCode;
      const res = await api.ingestComplaint({
        customerName: customerName.trim() || "Customer",
        customerReference: customerReference.trim() || `CUST-NGN-${Math.floor(100000 + Math.random() * 900000)}`,
        customerPhone: customerPhone.trim(),
        customerEmail: customerEmail.trim(),
        accountNumber: accountNumber.trim(),
        channel,
        categoryCode,
        categoryLabel,
        priority,
        summary: summary.trim(),
        narrative: narrative.trim(),
        transactionReference: transactionReference.trim() || undefined,
        amount: amount.trim() || undefined,
        sendAcknowledgement,
      });

      setResult({ reference: res.reference, complaintId: res.complaintId });
      toast(`Complaint ${res.reference} registered successfully!`, "success");
      if (onDone) onDone(res.reference, res.complaintId);
    } catch {
      toast("Complaint ingestion failed. Please try again.", "error");
    } finally {
      setSubmitting(false);
    }
  };

  return (
    <div className={`intake-container ${embedded ? "embedded" : "modal"}`}>
      {/* Top Header */}
      <div className="intake-header">
        <div>
          <div className="intake-pill-tag">
            <Sparkles size={13} aria-hidden="true" />
            <span>Hackathon Demo Intake Gateway</span>
          </div>
          <h2>File &amp; Ingest New Complaint</h2>
          <p className="muted">
            Simulate real customer complaint intake across banking channels with automated regulatory acknowledgment and AI triage.
          </p>
        </div>
        {onClose && (
          <button type="button" className="icon-button" aria-label="Close intake dialog" onClick={onClose}>
            <X size={18} aria-hidden="true" />
          </button>
        )}
      </div>

      {result ? (
        /* Result celebration panel */
        <div className="intake-success-card" role="region" aria-label="Complaint intake confirmation">
          <div className="success-badge-icon">
            <CheckCircle2 size={36} aria-hidden="true" />
          </div>
          <h3>Complaint Ingested Successfully</h3>
          <p className="intake-success-lead">
            The complaint has been ingested into RESOLVEIQ, timestamped with a cryptographic audit trail, and assigned an SLA clock.
          </p>

          <div className="intake-metrics-summary">
            <div>
              <span className="muted small">Reference</span>
              <strong className="mono intake-ref-highlight">{result.reference}</strong>
            </div>
            <div>
              <span className="muted small">Status</span>
              <Badge tone="info">NEW · Triage In Progress</Badge>
            </div>
            <div>
              <span className="muted small">Regulatory Acknowledgement</span>
              <strong className="text-success">
                {sendAcknowledgement ? "Dispatched (SMS & Email)" : "Channel Acknowledged"}
              </strong>
            </div>
            <div>
              <span className="muted small">Incident Clustering</span>
              <strong>Matched &amp; Correlated</strong>
            </div>
          </div>

          <div className="intake-success-actions">
            <Link
              href={`/complaints/${result.complaintId}`}
              className="button button-primary"
              onClick={() => {
                if (onClose) onClose();
              }}
            >
              <span>Open Case in Operator Desk</span>
              <ArrowRight size={16} aria-hidden="true" />
            </Link>
            <button
              type="button"
              className="button button-secondary"
              onClick={() => {
                setResult(null);
                clearForm();
              }}
            >
              <Plus size={15} aria-hidden="true" />
              <span>Log Another Complaint</span>
            </button>
            <Link
              href="/complaints"
              className="button button-ghost"
              onClick={() => {
                if (onClose) onClose();
              }}
            >
              <span>Back to Complaints Register</span>
            </Link>
          </div>
        </div>
      ) : (
        /* Intake Form */
        <form onSubmit={handleSubmit} className="intake-form">
          {/* Preset scenarios bar */}
          <div className="preset-bar-box">
            <div className="preset-bar-header">
              <span className="preset-label">
                <Zap size={14} aria-hidden="true" />
                <span>1-Click Hackathon Scenarios:</span>
              </span>
              <button type="button" className="preset-clear-link" onClick={clearForm}>
                <RefreshCw size={12} aria-hidden="true" />
                <span>Clear / Blank</span>
              </button>
            </div>
            <div className="preset-chips-scroll">
              {demoScenarios.map((scenario) => {
                const Icon = scenario.icon;
                const isSelected = activePreset === scenario.id;
                return (
                  <button
                    key={scenario.id}
                    type="button"
                    className={`preset-chip ${isSelected ? "active" : ""}`}
                    onClick={() => applyPreset(scenario)}
                  >
                    <Icon size={14} aria-hidden="true" />
                    <span className="preset-chip-title">{scenario.name}</span>
                    <span className="preset-chip-badge">{scenario.badge}</span>
                  </button>
                );
              })}
            </div>
          </div>

          {/* Two-column layout */}
          <div className="intake-columns">
            {/* Left: Customer & Transaction */}
            <div className="intake-col">
              <h3 className="intake-col-heading">
                <User size={15} aria-hidden="true" />
                <span>Customer &amp; Channel Details</span>
              </h3>

              <div className="field">
                <label htmlFor="customer-name">Customer Full Name</label>
                <input
                  id="customer-name"
                  type="text"
                  required
                  value={customerName}
                  onChange={(e) => setCustomerName(e.target.value)}
                  placeholder="e.g. Adaeze Okonkwo"
                />
              </div>

              <div className="intake-row-2">
                <div className="field">
                  <label htmlFor="customer-ref">Customer Reference</label>
                  <input
                    id="customer-ref"
                    type="text"
                    required
                    value={customerReference}
                    onChange={(e) => setCustomerReference(e.target.value)}
                    placeholder="e.g. CUST-NGN-084920"
                  />
                </div>
                <div className="field">
                  <label htmlFor="account-num">Account Number</label>
                  <input
                    id="account-num"
                    type="text"
                    value={accountNumber}
                    onChange={(e) => setAccountNumber(e.target.value)}
                    placeholder="e.g. 0128492019"
                  />
                </div>
              </div>

              <div className="intake-row-2">
                <div className="field">
                  <label htmlFor="customer-phone">Phone (SMS Notice)</label>
                  <input
                    id="customer-phone"
                    type="tel"
                    value={customerPhone}
                    onChange={(e) => setCustomerPhone(e.target.value)}
                    placeholder="+234 801 234 4567"
                  />
                </div>
                <div className="field">
                  <label htmlFor="customer-email">Email Address</label>
                  <input
                    id="customer-email"
                    type="email"
                    value={customerEmail}
                    onChange={(e) => setCustomerEmail(e.target.value)}
                    placeholder="customer@apexbank.ng"
                  />
                </div>
              </div>

              <div className="field">
                <label htmlFor="source-channel">Ingestion Channel</label>
                <select id="source-channel" value={channel} onChange={(e) => setChannel(e.target.value)}>
                  {channelOptions.map((c) => (
                    <option key={c} value={c}>
                      {c}
                    </option>
                  ))}
                </select>
              </div>

              <div className="intake-row-2">
                <div className="field">
                  <label htmlFor="disputed-amount">Disputed Amount</label>
                  <input
                    id="disputed-amount"
                    type="text"
                    value={amount}
                    onChange={(e) => setAmount(e.target.value)}
                    placeholder="e.g. 50,000 NGN"
                  />
                </div>
                <div className="field">
                  <label htmlFor="txn-ref">Transaction Reference</label>
                  <input
                    id="txn-ref"
                    type="text"
                    value={transactionReference}
                    onChange={(e) => setTransactionReference(e.target.value)}
                    placeholder="e.g. TXN-REF-894021"
                  />
                </div>
              </div>
            </div>

            {/* Right: Classification & Issue Narrative */}
            <div className="intake-col">
              <h3 className="intake-col-heading">
                <FileText size={15} aria-hidden="true" />
                <span>Complaint Classification &amp; Narrative</span>
              </h3>

              <div className="field">
                <label htmlFor="category">Category</label>
                <select id="category" value={categoryCode} onChange={(e) => setCategoryCode(e.target.value)}>
                  {categoryOptions.map((c) => (
                    <option key={c.code} value={c.code}>
                      {c.label}
                    </option>
                  ))}
                </select>
              </div>

              <div className="field">
                <label>Priority &amp; Regulatory SLA</label>
                <div className="priority-pill-selector" role="radiogroup" aria-label="Priority level">
                  {(["LOW", "MEDIUM", "HIGH", "CRITICAL"] as Priority[]).map((p) => {
                    const isSelected = priority === p;
                    const meta = priorityMeta[p];
                    const sla = p === "CRITICAL" ? "12h" : p === "HIGH" ? "24h" : p === "MEDIUM" ? "48h" : "72h";
                    return (
                      <button
                        key={p}
                        type="button"
                        className={`priority-select-btn tone-${meta.tone} ${isSelected ? "active" : ""}`}
                        onClick={() => setPriority(p)}
                      >
                        <span className="priority-name">{meta.label}</span>
                        <span className="priority-sla-tag">SLA {sla}</span>
                      </button>
                    );
                  })}
                </div>
              </div>

              <div className="field">
                <label htmlFor="summary">Issue Summary / Title</label>
                <input
                  id="summary"
                  type="text"
                  required
                  value={summary}
                  onChange={(e) => setSummary(e.target.value)}
                  placeholder="e.g. Dispenser timeout at ATM terminal 04"
                />
              </div>

              <div className="field">
                <label htmlFor="narrative">Detailed Customer Narrative</label>
                <textarea
                  id="narrative"
                  rows={4}
                  required
                  value={narrative}
                  onChange={(e) => setNarrative(e.target.value)}
                  placeholder="Full customer statement, circumstances, and error messages..."
                />
              </div>

              <div className="ack-toggle-box">
                <label className="checkbox-label">
                  <input
                    type="checkbox"
                    checked={sendAcknowledgement}
                    onChange={(e) => setSendAcknowledgement(e.target.checked)}
                  />
                  <span>
                    <strong>Automated Regulatory Acknowledgement</strong>
                    <small>
                      Queue instant regulatory SMS &amp; Email notice via Transactional Outbox upon ingestion.
                    </small>
                  </span>
                </label>
              </div>
            </div>
          </div>

          {/* Form Actions */}
          <div className="intake-form-actions">
            <button
              type="submit"
              className="button button-primary intake-submit-btn"
              disabled={submitting}
            >
              {submitting ? (
                <>
                  <RefreshCw size={16} aria-hidden="true" className="spin-icon" />
                  <span>Ingesting into RESOLVEIQ…</span>
                </>
              ) : (
                <>
                  <Sparkles size={16} aria-hidden="true" />
                  <span>Ingest &amp; File Complaint</span>
                </>
              )}
            </button>
            {onClose && (
              <button type="button" className="button button-secondary" onClick={onClose} disabled={submitting}>
                Cancel
              </button>
            )}
          </div>
        </form>
      )}
    </div>
  );
}
